
#!/usr/bin/env bash
# Generates reports and execution timestamp information
# into docs/reports/

set -uo pipefail

OUT=docs/reports
rm -rf "$OUT"
mkdir -p "$OUT"

TIMESTAMP_REPORT="$OUT/execution_timestamps.txt"

OVERALL_START=$(date +%s)
OVERALL_START_TIME=$(date -u +"%Y-%m-%dT%H:%M:%SZ")

# Initialize timestamp report
printf '%s\n' \
    "CI EXECUTION TIMESTAMP REPORT" \
    "================================" \
    "Overall Start: $OVERALL_START_TIME" \
    "Timezone: UTC" \
    "" > "$TIMESTAMP_REPORT"

# Record overall completion, even if a stage fails
finish_report() {
    EXIT_CODE=$?
    OVERALL_END=$(date +%s)
    OVERALL_END_TIME=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
    OVERALL_DURATION=$((OVERALL_END - OVERALL_START))

    {
        echo ""
        echo "================================"
        echo "Overall End: $OVERALL_END_TIME"
        echo "Total Execution Duration: ${OVERALL_DURATION} seconds"
        if [ "$EXIT_CODE" -eq 0 ]; then
            echo "Overall Status: PASSED"
        else
            echo "Overall Status: FAILED"
            echo "Exit Code: $EXIT_CODE"
        fi
    } >> "$TIMESTAMP_REPORT"
}

trap finish_report EXIT

# Run a stage and record its execution details
run_stage() {
    STAGE_NAME="$1"
    shift

    STAGE_START=$(date +%s)
    STAGE_START_TIME=$(date -u +"%Y-%m-%dT%H:%M:%SZ")

    echo ""
    echo ">> Starting: $STAGE_NAME"
    echo "Start time: $STAGE_START_TIME"

    "$@"
    STAGE_STATUS=$?

    STAGE_END=$(date +%s)
    STAGE_END_TIME=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
    STAGE_DURATION=$((STAGE_END - STAGE_START))

    {
        echo "$STAGE_NAME"
        echo "Start: $STAGE_START_TIME"
        echo "End: $STAGE_END_TIME"
        echo "Duration: ${STAGE_DURATION} seconds"
        if [ "$STAGE_STATUS" -eq 0 ]; then
            echo "Status: PASSED"
        else
            echo "Status: FAILED"
        fi
        echo ""
    } >> "$TIMESTAMP_REPORT"

    echo "End time: $STAGE_END_TIME"
    echo "Duration: ${STAGE_DURATION} seconds"

    return "$STAGE_STATUS"
}

# 1. Unit tests and line coverage
if ! run_stage "Unit Tests + Line Coverage" bash -c '
    set -e
    COVERAGE_FILE=.coverage.line pytest tests/unit \
      --html="docs/reports/unit_test_report.html" --self-contained-html \
      --junitxml="docs/reports/unit_test_junit.xml" \
      --cov=ctgs --cov-report="html:docs/reports/code_coverage_html"

    COVERAGE_FILE=.coverage.line coverage report -m \
      > "docs/reports/code_coverage_report.txt"
'; then
    exit 1
fi

# 2. Branch coverage
if ! run_stage "Branch Coverage" bash -c '
    set -e
    COVERAGE_FILE=.coverage.branch pytest tests/unit \
      --cov=ctgs --cov-branch \
      --cov-report="html:docs/reports/branch_coverage_html"

    COVERAGE_FILE=.coverage.branch coverage report -m \
      > "docs/reports/branch_coverage_report.txt"
'; then
    exit 1
fi

# 3. System validation
if ! run_stage "System Validation" bash -c '
    set -e
    pytest tests/system \
      --html="docs/reports/system_validation_report.html" \
      --self-contained-html \
      --junitxml="docs/reports/system_validation_junit.xml"
'; then
    exit 1
fi

# Remove .gitignore files generated by coverage
find "$OUT" -name .gitignore -delete

echo ""
echo "All reports written to $OUT/"
echo "Timestamp report: $TIMESTAMP_REPORT"
